export let lang = localStorage.getItem('mockLang') || 'he';
const idx = () => (lang === 'he' ? 0 : 1);

export function t(key, ...args) {
  const row = S[key];
  if (!row) return key;
  let s = row[idx()];
  args.forEach(a => { s = s.replace('%s', a); });
  return s;
}
export function nm(obj) { return obj ? obj[lang] || obj.he : ''; }
export function setLang(l) { lang = l; localStorage.setItem('mockLang', l); }
export function isRtl() { return lang === 'he'; }
